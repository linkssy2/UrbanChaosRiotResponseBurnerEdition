"""Generate the isolated exact decal body with bounded quad command batching.

Only the selected callback dispatch is integrated by the parent. No generated
original source is changed. Regeneration fails when its pinned body changes.
"""
from pathlib import Path
import hashlib

ROOT = Path(__file__).resolve().parents[1]
def extract(text, name):
    start = text.index('void sub_' + name + '(void)')
    return text[start:text.index('\n}\n', start) + 3]

def generate():
    original = extract((ROOT/'src/recomp/gen/recomp_0006.c').read_text(), '0009BF50')
    expected = '1822e68f0c17d7d60d3fa6bcd40b27d28a5b0852741649b9366cd47f48a9ac34'
    digest = hashlib.sha256(original.encode()).hexdigest()
    if digest != expected:
        raise RuntimeError('Original 9BF50 changed: ' + digest)
    body = original.replace('void sub_0009BF50(void)', 'static void uc_decal_restoration_body(void)', 1)
    body = body.replace('{\n', '{\n    UCDecalBatch batch = {0};\n', 1)
    anchor = 'loc_0009C12C: ;\n'
    assert body.count(anchor) == 1
    body = body.replace(anchor, anchor + '    batch = uc_decal_batch_begin(MEM32(esp + 0x1C), esp);\n')
    a = body.index('loc_0009C21F: ;\n')
    b = body.index('\nloc_0009C24D: ;', a)
    old = body[a:b]
    replacement = '''loc_0009C21F: ;
    if (batch.device) {
        uc_decal_batch_vertex(&batch, esp, esi, ebp);
    } else {
''' + old.removeprefix('loc_0009C21F: ;\n') + '\n    }\n'
    body = body[:a] + replacement + body[b:]
    return '/* Generated by scripts/prepare_decal_restoration.py. Original body SHA256: '+digest+' */\n' + body

if __name__ == '__main__':
    out = ROOT/'src/decal_restoration_body.inc'
    data = generate()
    out.write_text(data)
    print(out)
